"""Markdown report generated from results.json and errors.jsonl (PRD §15, §19)."""

from __future__ import annotations

from collections import Counter
from typing import Any


def _fmt(value: Any, digits: int = 2) -> str:
    if value is None:
        return "–"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def render_report(results: dict[str, Any], errors: list[dict[str, Any]]) -> str:
    inputs = results["inputs"]
    lines = [f"# {results['experiment']} — run {results['run_id']}", ""]
    if results.get("mock"):
        lines += [
            "> **MOCK RUN.** Every system was replaced by a mock model that writes digital",
            "> silence. These numbers test the pipeline only. They are not evidence about any",
            "> named model: a silent mock segment is not a failure of that model.",
            "",
        ]
    lines += [
        f"- Mode: {results['mode']}",
        f"- Started: {results['started_at']} · Finished: {results['finished_at']}",
        f"- Utterances: {inputs['utterances']} ({_by_split(inputs['utterances_by_split'])})"
        f" · Segments: {inputs['segments']}",
        f"- Config sha256: `{inputs['config_sha256'][:12]}` · Manifest sha256: "
        f"`{inputs['manifest_sha256'][:12]}` · Frozen splits: "
        f"`{inputs['frozen_splits_checksum'][:12]}`",
        f"- Normalizer: `{inputs['normalizer_version']}` · Cache: {inputs['cache']}",
        "",
        "## Systems",
        "",
        "| System | Model | Status | OK / total | Silent | Errors | Cached | Audio s | RTF |"
        " Completeness gate |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for s in results["systems"]:
        model = f"{s['model']['model_id']} {s['model']['version']}"
        status = "ran" if s["ran"] else f"not run: {s['blocked_reason']}"
        lines.append(
            f"| {s['system_id']} | {model} | {status} | {s['segments_ok']} / "
            f"{s['segments_total']} | {_fmt(s.get('segments_silent'))} | "
            f"{_fmt(s.get('segments_error'))} | {_fmt(s.get('segments_cached'))} | "
            f"{_fmt(s.get('audio_seconds'))} | {_fmt(s.get('real_time_factor'), 3)} | "
            f"**{s['gate_completeness']}** |"
        )

    lines += ["", "## Release gates", ""]
    for gate, value in results["gates"].items():
        if isinstance(value, dict):
            value = ", ".join(f"{k}: {v}" for k, v in value.items())
        lines.append(f"- **{gate}**: {value}")

    lines += ["", "## Checks", ""]
    lines += [f"- {name}: {state}" for name, state in results["checks"].items()]

    lines += ["", "## Errors", ""]
    if not errors:
        lines.append("None.")
    else:
        counts = Counter((e["system_id"], e["error"]) for e in errors)
        lines += ["| System | Error | Count |", "|---|---|---|"]
        for (system, error), n in sorted(counts.items()):
            lines.append(f"| {system} | {error} | {n} |")
        tag_counts = Counter(tag.upper() for e in errors for tag in e.get("tags", []))
        if tag_counts:
            lines += [
                "",
                "Failed segments by Tamil taxonomy tag: "
                + ", ".join(f"{tag} {n}" for tag, n in sorted(tag_counts.items())),
            ]

    if results.get("warnings"):
        lines += ["", "## Warnings", ""]
        lines += [f"- {w}" for w in results["warnings"]]

    lines += [
        "",
        "---",
        "Generated by `tamil-tts experiment run`. Contains ids, checksums and counts only;",
        "no Tamil text, transcripts or audio.",
        "",
    ]
    return "\n".join(lines)


def _by_split(counts: dict[str, int]) -> str:
    return ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) or "none"
